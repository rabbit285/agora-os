"""Audit actions, said in a sentence.

The audit trail stores machine names — `compliance.gap.remediation_generated`
— because they have to be stable, greppable, and safe to filter on. A
person reading a task's history should never see one. This module is the
single place that translation happens, so the same event reads the same
way wherever it surfaces.

Phrasing is past tense and specific about *who*: "Veyntra" for work the
system did on its own, an unqualified verb for work a person did. A feed
that says "evidence approved" for both an automatic rule and a human
decision hides the distinction that makes the trail worth keeping.
"""

from __future__ import annotations

from typing import Any

# Only actions that can appear on a remediation task or the gap behind
# it. An action with no entry is not shown rather than shown raw — a
# feed is allowed to be incomplete, but never to leak an internal name.
EVENT_PHRASES: dict[str, str] = {
    # The gap's own life.
    "compliance.gap.created": "Gap identified during assessment",
    "compliance.gap.remediation_generated": "Remediation plan generated by Veyntra",
    "compliance.gap.remediation_updated": "Remediation plan updated after new evidence",
    "compliance.gap.task_created": "Remediation task raised",
    "compliance.gap.evidence_detected": "New evidence detected",
    "compliance.gap.control_reassessed": "Control reassessed",
    "compliance.gap.resolved": "Gap resolved",
    # A policy's governance life.
    "compliance.policy.detected": "Policy found in an uploaded document",
    "compliance.policy.created": "Policy record created",
    "compliance.policy.governance_updated": "Governance details updated",
    "compliance.policy.approved": "Approved",
    "compliance.policy.status_changed": "Status changed",
    "compliance.policy.version_replaced": "Document replaced with a new version",
    "compliance.policy.new_version_detected": "A newer document may supersede this",
    # The task's own life.
    "core.task.created": "Task created",
    "core.task.status_changed": "Status changed",
    "core.task.checklist_updated": "Checklist updated",
    "core.task.assigned": "Owner assigned",
    "core.task.commented": "Comment added",
    "core.task.evidence_attached": "Evidence attached",
}


def describe(action: str, after_state: dict[str, Any] | None = None) -> str | None:
    """One line for one event, or None if it has no reader-facing form.

    `after_state` sharpens the line where the difference matters — a
    status change to `done` because the gap closed is a different fact
    from someone marking it done by hand, and the feed should say which.
    """
    phrase = EVENT_PHRASES.get(action)
    if phrase is None:
        return None

    state = after_state or {}
    if action == "core.task.status_changed":
        new_status = str(state.get("status", "")).replace("_", " ")
        if state.get("closed_by") == "gap_resolved":
            return "Closed automatically — the gap it was raised for is resolved"
        if state.get("reason") == "evidence_found":
            return "Ready for review — evidence found, awaiting a human verdict"
        return f"Status changed to {new_status}" if new_status else phrase
    if action == "compliance.gap.evidence_detected":
        filename = state.get("filename")
        return f"New evidence detected: {filename}" if filename else phrase
    if action == "compliance.gap.remediation_generated":
        count = state.get("checklist_items")
        if count:
            return f"{phrase} — {count} steps"
    if action == "compliance.gap.remediation_updated":
        reviewed = state.get("evidence_reviewed")
        if reviewed:
            noun = "document" if reviewed == 1 else "documents"
            return f"Remediation plan updated after reading {reviewed} {noun}"
    if action == "core.task.assigned":
        owner = state.get("assignee_name")
        if owner:
            return f"Owner assigned: {owner}"
    return phrase


__all__ = ["EVENT_PHRASES", "describe"]
