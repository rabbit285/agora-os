"use client";

import { useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";

import { PageHeader } from "@/components/page-header";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { apiFetch } from "@/lib/api";
import type { AIAgentConfig } from "@/lib/types";

function AIAgentForm({ config }: { config: AIAgentConfig | null }) {
  const queryClient = useQueryClient();
  const [enabled, setEnabled] = useState(config?.enabled ?? false);
  const [autoSend, setAutoSend] = useState(config?.auto_send_grounded_replies ?? false);

  const save = useMutation({
    mutationFn: () =>
      apiFetch<AIAgentConfig>("/api/v1/support/ai-agent-config", {
        method: "PUT",
        body: { enabled, auto_send_grounded_replies: autoSend },
      }),
    onSuccess: () => queryClient.invalidateQueries({ queryKey: ["support", "ai-agent-config"] }),
  });

  return (
    <Card>
      <CardContent className="flex flex-col gap-4 pt-6">
        <label className="flex items-center gap-2 text-sm text-neutral-700">
          <input
            type="checkbox"
            checked={enabled}
            onChange={(e) => setEnabled(e.target.checked)}
          />
          Enable the AI Agent for this organization
        </label>
        <label className="flex items-center gap-2 text-sm text-neutral-700">
          <input
            type="checkbox"
            checked={autoSend}
            disabled={!enabled}
            onChange={(e) => setAutoSend(e.target.checked)}
          />
          Auto-send grounded replies (skip agent approval when the Copilot&apos;s answer is
          genuinely grounded in knowledge base content)
        </label>
        <p className="text-xs text-neutral-400">
          Drafted replies are always generated by the real retrieval-grounded AI Copilot. When
          the knowledge base has nothing relevant, the honest &ldquo;no evidence&rdquo; answer is
          never auto-sent, even with this setting on — it always waits for agent approval.
        </p>
        <Button disabled={save.isPending} onClick={() => save.mutate()} className="self-start">
          Save
        </Button>
      </CardContent>
    </Card>
  );
}

export default function AIAgentConfigPage() {
  const { data: config, isLoading } = useQuery<AIAgentConfig | null>({
    queryKey: ["support", "ai-agent-config"],
    queryFn: () => apiFetch<AIAgentConfig | null>("/api/v1/support/ai-agent-config"),
  });

  return (
    <div>
      <PageHeader
        title="AI Agent"
        description="Configure how the Support AI Agent drafts and sends replies (spec §32)."
      />
      {isLoading ? (
        <p className="text-sm text-neutral-500">Loading…</p>
      ) : (
        <AIAgentForm key={config?.id ?? "new"} config={config ?? null} />
      )}
    </div>
  );
}
