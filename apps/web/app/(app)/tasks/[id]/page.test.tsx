function route(path: string): unknown {
  if (path === `/api/v1/tasks/${TASK_ID}`) return TASK;
  if (path === `/api/v1/compliance/gaps/${GAP_ID}`) return GAP;
  if (path === `/api/v1/tasks/${TASK_ID}/activity`) return ACTIVITY;
  if (path === `/api/v1/tasks/${TASK_ID}/comments`) return [];
  if (path === `/api/v1/tasks/${TASK_ID}/evidence`) return [];
  throw new Error(`unexpected fetch: ${path}`);
}

/** The page reads its route params with `use()`, so the first render
 * suspends. jsdom never drives the resumption on its own — without the
 * Suspense boundary and the `act` flush the tree stays empty and every
 * assertion below reads as a product failure rather than a test-harness
 * one. */
async function renderPage() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  await act(async () => {
    render(
      <QueryClientProvider client={client}>
        <Suspense fallback={null}>
          <TaskDetailPage params={Promise.resolve({ id: TASK_ID })} />
        </Suspense>
      </QueryClientProvider>
    );
  });
}

describe("remediation task detail", () => {
  beforeEach(() => {
    mockedApiFetch.mockReset();
    mockedApiFetch.mockImplementation((path: string) => Promise.resolve(route(path)) as never);
  });

  it("never shows a raw entity id or a raw priority label", async () => {
    await renderPage();
    await screen.findByText(/Remediate Art. 4/);

    await waitFor(() => expect(screen.getByText(/Related gap/)).toBeInTheDocument());

    // The two leaks in the report: `linked to compliance_gap: <uuid>` and
    // `priority: high`.
    expect(screen.queryByText(new RegExp(GAP_ID))).not.toBeInTheDocument();
    expect(screen.queryByText(/compliance_gap/)).not.toBeInTheDocument();
    expect(screen.queryByText(/priority: high/)).not.toBeInTheDocument();
    expect(screen.getByText("High priority")).toBeInTheDocument();
  });

  it("names the related gap in words and links to it", async () => {
    await renderPage();
    const related = await screen.findByText("AI literacy training evidence incomplete");
    const link = related.closest("a");
    expect(link).not.toBeNull();
    expect(link?.getAttribute("href")).toBe(`/compliance/frameworks/${GAP.framework_id}`);
  });

  it("renders the plan rather than an empty shell", async () => {
    await renderPage();
    await screen.findByText(/no evidence of completed AI literacy training/);

    expect(screen.getByText("Problem")).toBeInTheDocument();
    expect(screen.getByText("Why this is open")).toBeInTheDocument();
    expect(screen.getByText("What to do")).toBeInTheDocument();
    expect(
      screen.getByText("Attendance or completion records naming the people trained")
    ).toBeInTheDocument();
    expect(screen.getByText(/employee-handbook.pdf/)).toBeInTheDocument();
    expect(screen.getByText(/Support Copilot/)).toBeInTheDocument();
    expect(screen.getByText(/Suggested owner: HR \/ People/)).toBeInTheDocument();

    // The checklist arrives populated — the reported bug was an empty one.
    expect(screen.getByText("Deliver the training")).toBeInTheDocument();
    expect(screen.queryByText("No checklist items yet.")).not.toBeInTheDocument();
  });

  it("shows activity as sentences, never as audit action names", async () => {
    await renderPage();
    await screen.findByText("Gap identified during assessment");
    expect(
      screen.getByText("Remediation plan generated by Veyntra — 2 steps")
    ).toBeInTheDocument();
    expect(screen.queryByText(/compliance\.gap\./)).not.toBeInTheDocument();
  });
});
