"use client";

import { useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";

import { PageHeader } from "@/components/page-header";
import { StatusBadge } from "@/components/status-badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { apiFetch } from "@/lib/api";
import type { Meeting, SalesAccount } from "@/lib/types";

export default function MeetingsPage() {
  const queryClient = useQueryClient();
  const [title, setTitle] = useState("");
  const [accountId, setAccountId] = useState("");
  const [scheduledAt, setScheduledAt] = useState("");

  const { data: meetings } = useQuery<Meeting[]>({
    queryKey: ["sales", "meetings"],
    queryFn: () => apiFetch<Meeting[]>("/api/v1/sales/meetings"),
  });
  const { data: accounts } = useQuery<SalesAccount[]>({
    queryKey: ["sales", "accounts"],
    queryFn: () => apiFetch<SalesAccount[]>("/api/v1/sales/accounts"),
  });

  const createMeeting = useMutation({
    mutationFn: () =>
      apiFetch<Meeting>("/api/v1/sales/meetings", {
        method: "POST",
        body: {
          title,
          account_id: accountId || null,
          scheduled_at: new Date(scheduledAt).toISOString(),
        },
      }),
    onSuccess: () => {
      setTitle("");
      setAccountId("");
      setScheduledAt("");
      queryClient.invalidateQueries({ queryKey: ["sales", "meetings"] });
    },
  });

  const generatePrepNotes = useMutation({
    mutationFn: (meetingId: string) =>
      apiFetch<Meeting>(`/api/v1/sales/meetings/${meetingId}/prep-notes`, { method: "POST" }),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["sales", "meetings"] });
    },
  });

  return (
    <div>
      <PageHeader
        title="Meetings"
        description="Meeting Assistant: prep notes are generated by the real, retrieval-grounded AI Copilot (spec §26)."
      />
      <Card className="mb-4">
        <CardContent className="flex flex-col gap-3 pt-6">
          <Input
            placeholder="Meeting title"
            value={title}
            onChange={(e) => setTitle(e.target.value)}
          />
          <select
            className="h-9 rounded-md border border-[var(--border-strong)] bg-[var(--bg-surface)] px-3 text-sm"
            value={accountId}
            onChange={(e) => setAccountId(e.target.value)}
          >
            <option value="">No linked account</option>
            {accounts?.map((account) => (
              <option key={account.id} value={account.id}>
                {account.name}
              </option>
            ))}
          </select>
          <Input
            type="datetime-local"
            value={scheduledAt}
            onChange={(e) => setScheduledAt(e.target.value)}
          />
          <Button
            disabled={!title.trim() || !scheduledAt || createMeeting.isPending}
            onClick={() => createMeeting.mutate()}
            className="self-start"
          >
            Schedule meeting
          </Button>
        </CardContent>
      </Card>
      {meetings?.length === 0 && <p className="text-sm text-[var(--fg-muted)]">No meetings yet.</p>}
      <div className="flex flex-col gap-2">
        {meetings?.map((meeting) => (
          <Card key={meeting.id}>
            <CardContent className="pt-6">
              <div className="mb-1 flex items-center justify-between">
                <div className="font-medium text-[var(--fg-default)]">{meeting.title}</div>
                <StatusBadge status={meeting.status} />
              </div>
              <div className="mb-2 text-xs text-[var(--fg-subtle)]">
                {new Date(meeting.scheduled_at).toLocaleString()}
              </div>
              {meeting.prep_notes ? (
                <p className="text-sm text-[var(--fg-muted)]">{meeting.prep_notes}</p>
              ) : (
                <Button
                  size="sm"
                  variant="outline"
                  disabled={generatePrepNotes.isPending}
                  onClick={() => generatePrepNotes.mutate(meeting.id)}
                >
                  Generate prep notes
                </Button>
              )}
            </CardContent>
          </Card>
        ))}
      </div>
    </div>
  );
}
