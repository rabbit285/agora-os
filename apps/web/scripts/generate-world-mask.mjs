/**
 * Bakes Natural Earth's 110m land polygons into a compact bit-packed land
 * mask, committed as `lib/world-land-mask.ts`.
 *
 * Run with: node scripts/generate-world-mask.mjs
 *
 * Why precompute: the decorative world map only needs to know "is this
 * grid cell land?". Shipping TopoJSON plus a client-side projection to
 * answer that would put ~100KB of geo data and a polygon test into the
 * marketing bundle for a background graphic. The mask is ~2.7KB of base64
 * with no runtime dependency, and `world-atlas`/`topojson-client` stay
 * devDependencies used only by this script.
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/land-110m.json");

// Equirectangular grid. Latitude is clipped rather than spanning the full
// -90..90: Antarctica reads as a solid bar across the bottom of a dot map
// and the high Arctic is empty, so both would only add noise to what is a
// background texture.
const COLS = 200;
const ROWS = 100;
const LAT_MIN = -56;
const LAT_MAX = 80;

const land = feature(topology, topology.objects.land);

/** Every linear ring in the land geometry, each with a cached bounding box
 * so the point test can reject the vast majority of rings immediately —
 * without this the 20k cells x ~130 rings test takes minutes. */
const rings = [];
for (const f of land.features) {
  const polygons =
    f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      let minX = Infinity;
      let minY = Infinity;
      let maxX = -Infinity;
      let maxY = -Infinity;
      for (const [x, y] of ring) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
      rings.push({ ring, minX, minY, maxX, maxY });
    }
  }
}

/** Standard even-odd ray casting. Holes work out naturally: a point inside
 * both an outer ring and an inner one is crossed an even number of times
 * overall and so counts as sea. */
function insideRing(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

function isLand(lon, lat) {
  let inside = false;
  for (const r of rings) {
    if (lon < r.minX || lon > r.maxX || lat < r.minY || lat > r.maxY) continue;
    if (insideRing(r.ring, lon, lat)) inside = !inside;
  }
  return inside;
}

const bytes = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let landCells = 0;

for (let row = 0; row < ROWS; row++) {
  // Sample the middle of each cell, and go top-down so row 0 is the
  // northern edge — matching how the renderer lays the grid out.
  const lat = LAT_MAX - ((row + 0.5) / ROWS) * (LAT_MAX - LAT_MIN);
  for (let col = 0; col < COLS; col++) {
    const lon = -180 + ((col + 0.5) / COLS) * 360;
    if (isLand(lon, lat)) {
      const bit = row * COLS + col;
      bytes[bit >> 3] |= 128 >> (bit & 7);
      landCells++;
    }
  }
}

const base64 = Buffer.from(bytes).toString("base64");

writeFileSync(
  new URL("../lib/world-land-mask.ts", import.meta.url),
  `// GENERATED by scripts/generate-world-mask.mjs — do not edit by hand.
// Natural Earth 110m land polygons (public domain), rasterized to a
// ${COLS}x${ROWS} equirectangular grid clipped to ${LAT_MIN}..${LAT_MAX} degrees
// latitude and bit-packed, MSB first, row-major from the northern edge.
// ${landCells} of ${COLS * ROWS} cells are land.

export const WORLD_MASK_COLS = ${COLS};
export const WORLD_MASK_ROWS = ${ROWS};

const PACKED =
  "${base64}";

/** Unpacks to one boolean per grid cell, row-major. */
export function decodeWorldMask(): Uint8Array {
  const raw = atob(PACKED);
  const cells = new Uint8Array(WORLD_MASK_COLS * WORLD_MASK_ROWS);
  for (let i = 0; i < cells.length; i++) {
    cells[i] = (raw.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1;
  }
  return cells;
}
`,
  "utf8",
);

console.log(`wrote lib/world-land-mask.ts — ${landCells} land cells, ${base64.length} base64 chars`);
